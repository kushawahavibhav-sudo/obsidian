/**
 * OBSIDIAN — image optimisation pass.
 * Re-encodes every downloaded photo into responsive WebP variants and writes
 * an <img srcset> manifest for the React components to consume.
 *
 * Usage: node scripts/optimize-images.mjs
 */
import { readdir, writeFile, rm, stat, mkdir, rename, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'public', 'images');
const TMP = path.join(ROOT, '.img-tmp');
const STAGE = path.join(TMP, 'stage');

const WIDTHS = [480, 900, 1440, 2000];

/** Windows occasionally keeps a transient handle on a just-written file. */
async function safeRm(target) {
  for (let i = 0; i < 6; i++) {
    try {
      await rm(target, { recursive: true, force: true, maxRetries: 3, retryDelay: 250 });
      return;
    } catch {
      await new Promise((r) => setTimeout(r, 400 * (i + 1)));
    }
  }
}

async function main() {
  const files = (await readdir(OUT)).filter((f) => f.endsWith('.webp'));
  await safeRm(TMP);
  await mkdir(STAGE, { recursive: true });

  const manifest = {};
  let before = 0;
  let after = 0;

  for (const file of files) {
    const src = path.join(OUT, file);
    const base = file.replace(/\.webp$/, '');

    // Stage the source so sharp never holds a lock on the file we overwrite.
    const staged = path.join(STAGE, file);
    await copyFile(src, staged);

    const meta = await sharp(staged).metadata();
    before += (await stat(staged)).size;

    const variants = [];
    for (const w of WIDTHS) {
      if (w > meta.width && w !== WIDTHS[0]) continue;
      const out = path.join(TMP, `${base}-${w}.webp`);
      await sharp(staged)
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: 74, effort: 6 })
        .toFile(out);
      variants.push({ w, file: `${base}-${w}.webp` });
    }

    // Publish every variant alongside the originals.
    for (const v of variants) {
      await rename(path.join(TMP, v.file), path.join(OUT, v.file));
    }

    // Largest variant becomes the canonical file so existing references keep working.
    const largest = variants[variants.length - 1];
    await safeRm(src);
    await copyFile(path.join(OUT, largest.file), src);
    after += (await stat(src)).size;

    manifest[base] = {
      src: `/images/${file}`,
      width: meta.width,
      height: meta.height,
      srcSet: variants.map((v) => `/images/${v.file} ${v.w}w`).join(', '),
    };

    console.log(`  ok  ${base.padEnd(30)} ${variants.length} variants  ${meta.width}x${meta.height}`);
  }

  await safeRm(TMP);
  await writeFile(
    path.join(ROOT, 'src', 'lib', 'images.ts'),
    `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.\n` +
      `export type ImageAsset = { src: string; width: number; height: number; srcSet: string };\n\n` +
      `export const images: Record<string, ImageAsset> = ${JSON.stringify(manifest, null, 2)};\n`,
    'utf8'
  );

  console.log(
    `\nOptimised: ${(before / 1024 / 1024).toFixed(2)} MB -> ${(after / 1024 / 1024).toFixed(2)} MB canonical\nWrote src/lib/images.ts`
  );
}

main();
